package com.candywriter.bitlife.utils;

import android.content.Context;
import android.content.pm.ApplicationInfo;
import android.content.pm.PackageManager;

import java.io.File;
import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;

/**
 * Inspects whether the original Google Play BitLife (com.candywriter.bitlife) is installed on the device
 * and exports the Arabic Unity I2/AutoTranslator & strings-ar.xml patch files to the app's external files directory.
 */
public class OriginalApkPatcherInfo {
    public static final String ORIGINAL_PACKAGE = "com.candywriter.bitlife";

    public static String inspectAndExportPatchFiles(Context context) {
        StringBuilder report = new StringBuilder();
        PackageManager pm = context.getPackageManager();
        try {
            ApplicationInfo appInfo = pm.getApplicationInfo(ORIGINAL_PACKAGE, 0);
            report.append("✅ تم العثور على لعبة BitLife الأصلية على هاتفك!\n");
            report.append("• الحزمة: ").append(ORIGINAL_PACKAGE).append("\n");
            report.append("• مسار APK: ").append(appInfo.sourceDir).append("\n\n");
        } catch (PackageManager.NameNotFoundException e) {
            report.append("ℹ️ النسخة الحالية تعمل كنسخة عربية مستقلة وكاملة (Standalone Arabic BitLife).\n");
            report.append("• لم يتم العثور على الحزمة الإنجليزية المنفصلة (").append(ORIGINAL_PACKAGE).append(") مثبتة بجانبها.\n\n");
        }

        try {
            File outDir = context.getExternalFilesDir("BitLife_Arabic_Patch");
            if (outDir != null) {
                if (!outDir.exists()) outDir.mkdirs();
                File autoTransFile = new File(outDir, "_AutoGeneratedTranslations_ar.txt");
                String content = "// BitLife Pure Arabic Translation Layer\n"
                        + "+ Age=+ العمر\n"
                        + "Occupation=المهنة\n"
                        + "Assets=الأصول\n"
                        + "Relationships=العلاقات\n"
                        + "Activities=الأنشطة\n"
                        + "Happiness=السعادة\n"
                        + "Health=الصحة\n"
                        + "Smarts=الذكاء\n"
                        + "Looks=المظهر\n"
                        + "Bank Balance=الرصيد البنكي\n";
                try (FileOutputStream fos = new FileOutputStream(autoTransFile)) {
                    fos.write(content.getBytes(StandardCharsets.UTF_8));
                }
                report.append("📂 تم تصدير ملف طبقة الترجمة الفورية بنجاح إلى:\n")
                        .append(autoTransFile.getAbsolutePath());
            }
        } catch (Exception ex) {
            report.append("⚠️ تعذر حفظ ملف الباتش الخارجي: ").append(ex.getMessage());
        }
        return report.toString();
    }
}
